/*
SPECIAL NUMERICAL LITERALS
*/
console.log("infinity: ", Infinity); // Output: Infinity
console.log("1 / 0: ", 1 / 0); // Output: Infinity
console.log("-1 / 0: ", -1 / 0); // Output: -Infinity
console.log("NaN: ", NaN); // Output: NaN
console.log("0 / 0: ", 0 / 0); // Output: NaN
console.log("isNaN(NaN): ", isNaN(NaN)); // Output: true
console.log("typeof infinity:", typeof Infinity); // Output: number
